type StopInput = Partial<GuideStop> & {
  id: string;
  poiId?: string;
  name: string;
  coordinates: [number, number];
  description: string;
  neighborhood?: string;
  sourcePhoto?: string;
  mapQuery?: string;
  editorialUrls?: string[];
  platformUrls?: string[];
};

function stop(input: StopInput): GuideStop {
  const {
    id,
    poiId,
    name,
    coordinates,
    description,
    neighborhood,
    sourcePhoto,
    mapQuery,
    editorialUrls = [],
    platformUrls = [],
    sourceEvidence,
    imageSourceUrl,
    officialUrl,
    bookingUrl,
    ...rest
  } = input;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${name} Hong Kong`);
  const imageUrl = imageSourceUrl ?? sourcePhoto ?? images.victoriaPeak;
  const officialEvidence = sourceEvidence?.officialUrl ?? officialUrl ?? bookingUrl ?? platformUrls[0];
  const sourceUrls = [
    officialEvidence,
    bookingUrl,
    mapUrl,
    imageUrl,
    ...editorialUrls,
    ...platformUrls,
    ...(input.sourceUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id,
    poiId: poiId ?? `hong-kong-venue-${id.replace(/^hong-kong-/, "")}`,
    name,
    coordinates,
    description,
    subcategory: neighborhood,
    photo: imageUrl,
    imageSourceUrl: imageUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl: imageUrl,
      editorialUrls,
      platformUrls,
      checkedAt,
      notes: "Official, platform, or venue-controlled page plus Google Maps search/listing checked for current status; no permanent-closure warning found in the source set.",
      ...sourceEvidence,
    },
    ...(officialUrl ? { officialUrl } : {}),
    ...(bookingUrl ? { bookingUrl } : {}),
    ...rest,
  };
}

