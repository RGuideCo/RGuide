function stop(input: StopInput): GuideStop {
  const mapUrl = maps(input.mapQuery ?? `${input.name} Venice Italy`);
  const imageSourceUrl = input.imageSourceUrl ?? input.officialUrl;
  const photo = input.photo ?? verifiedVenuePhotos[input.name] ?? imageSourceUrl;
  const sourceUrls = [
    input.officialUrl,
    input.bookingUrl,
    mapUrl,
    imageSourceUrl,
    ...(input.editorialUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id: input.id,
    name: input.name,
    coordinates: input.coordinates,
    description: input.description,
    venueKind: input.venueKind,
    foodServiceType: input.foodServiceType,
    cuisineTypes: input.cuisineTypes,
    nightlifeType: input.nightlifeType,
    musicGenres: input.musicGenres,
    lodgingType: input.lodgingType,
    subcategory: input.subcategory,
    attributeTags: input.attributeTags,
    price: input.price,
    priceSource: input.priceSource,
    bookingUrl: input.bookingUrl,
    officialUrl: input.officialUrl,
    hours: input.hours,
    photo,
    imageSourceUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: input.officialUrl,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl,
      editorialUrls: input.editorialUrls ?? [],
      checkedAt,
      notes:
        "Official venue, property, museum, transport, market, ticketing, or booking evidence was checked alongside a current map query. Hours reproduce the published schedule or name the exact seasonal, weather, performance, reservation, market-day, or transport-timetable dependency.",
    },
  };
}

