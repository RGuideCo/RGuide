type StopOptions = Partial<GuideStop> & {
  sourcePhoto: string;
  mapQuery?: string;
  editorialUrls?: string[];
};

function stop(id: string, name: string, coordinates: [number, number], description: string, options: StopOptions): GuideStop {
  const {
    sourcePhoto,
    mapQuery,
    editorialUrls = [],
    sourceEvidence,
    imageSourceUrl,
    officialUrl,
    bookingUrl,
    ...rest
  } = options;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${name} Prague`);
  const officialEvidence = sourceEvidence?.officialUrl ?? officialUrl ?? bookingUrl;
  const imageUrl = imageSourceUrl ?? sourcePhoto;
  const sourceUrls = [
    officialEvidence,
    mapUrl,
    imageUrl,
    ...editorialUrls,
    ...(options.sourceUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id,
    name,
    coordinates,
    description,
    hours: { default: "Open and active in current source set; hours vary by day. Check the official site or Google Maps before going." },
    photo: sourcePhoto,
    imageSourceUrl: imageUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl: imageUrl,
      editorialUrls,
      checkedAt,
      notes: "Official/property page and Google Maps listing/search checked for current status; no permanent-closure warning found in the source set.",
      ...sourceEvidence,
    },
    ...(officialUrl ? { officialUrl } : {}),
    ...(bookingUrl ? { bookingUrl } : {}),
    ...rest,
  };
}

