function source(name: string, url: string): ListSource {
  return { name, url };
}

function maps(query: string) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

function commonsPhoto(fileName: string) {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(fileName)}`;
}

function commonsSource(fileName: string) {
  return `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(fileName).replace(/%20/g, "_")}`;
}

function stop(input: StopInput): GuideStop {
  const mapUrl = maps(input.mapQuery ?? `${input.name} Kyoto Japan`);
  const platformUrls = [input.bookingUrl, ...(input.platformUrls ?? [])].filter(Boolean) as string[];
  const sourceUrls = [
    input.officialUrl,
    input.currentStatusUrl,
    mapUrl,
    input.photo,
    input.imageSourceUrl,
    ...platformUrls,
    ...(input.editorialUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id: input.id,
    name: input.name,
    coordinates: input.coordinates,
    description: input.description,
    venueKind: input.venueKind,
    foodServiceType: input.foodServiceType,
    cuisineTypes: input.cuisineTypes,
    nightlifeType: input.nightlifeType,
    musicGenres: input.musicGenres,
    lodgingType: input.lodgingType,
    subcategory: input.subcategory,
    attributeTags: input.attributeTags,
    price: input.price,
    priceSource: input.priceSource,
    bookingUrl: input.bookingUrl,
    officialUrl: input.officialUrl,
    hours: input.hours,
    photo: input.photo,
    imageSourceUrl: input.imageSourceUrl,
    imageSourceName:
      input.imageSourceName ??
      (input.imageSourceUrl.includes("wikimedia.org") ? "Wikimedia Commons" : "Official venue media"),
    imageCredit: input.imageCredit,
    imageLicense: input.imageLicense,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: input.officialUrl,
      mapUrl,
      currentStatusUrl: input.currentStatusUrl ?? input.officialUrl,
      imageSourceUrl: input.imageSourceUrl,
      editorialUrls: input.editorialUrls ?? [],
      platformUrls,
      checkedAt,
      notes:
        "Official venue or property information, current map evidence, image provenance, and the linked editorial or booking sources were checked on the stated date. Hours preserve the named official schedule and exact seasonal, performance, reservation, or public-access dependency.",
    },
  };
}

function sourcesFor(stops: GuideStop[], editorialSources: ListSource[]) {
  const all = [
    ...editorialSources,
    ...stops.map((item) => source(`${item.name} official`, item.officialUrl ?? maps(`${item.name} Kyoto Japan`))),
  ];
  return [...new Map(all.map((item) => [item.url, item])).values()];
}

