type StopOptions = Partial<GuideStop> & {
  sourcePhoto: string;
  officialUrl: string;
  editorialUrls?: string[];
  mapQuery?: string;
};

function stop(
  id: string,
  name: string,
  coordinates: [number, number],
  description: string,
  options: StopOptions,
): GuideStop {
  const {
    sourcePhoto,
    officialUrl,
    editorialUrls = [],
    mapQuery,
    bookingUrl,
    sourceEvidence,
    imageSourceUrl,
    sourceUrls: extraSourceUrls = [],
    ...rest
  } = options;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${name} Melbourne Australia`);
  const imageUrl = imageSourceUrl ?? sourcePhoto;
  const officialEvidence = sourceEvidence?.officialUrl ?? officialUrl ?? bookingUrl;
  const sourceUrls = [
    officialEvidence,
    mapUrl,
    imageUrl,
    ...editorialUrls,
    ...extraSourceUrls,
  ].filter(Boolean) as string[];

  return {
    id,
    name,
    coordinates,
    description,
    photo: sourcePhoto,
    imageSourceUrl: imageUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: sourceEvidence?.currentStatusUrl ?? officialEvidence,
      imageSourceUrl: imageUrl,
      editorialUrls,
      checkedAt,
      notes:
        "Checked against an official venue or operator page, current map evidence, and category sources on 2026-07-15; candidates with current closure notices were excluded.",
      ...sourceEvidence,
    },
    officialUrl,
    ...(bookingUrl ? { bookingUrl } : {}),
    ...rest,
  };
}

