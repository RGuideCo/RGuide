type StopOptions = Partial<GuideStop> & {
  editorialUrls?: string[];
  mapQuery?: string;
};

function stop(id: string, placeKey: string, note: string, options: StopOptions = {}): GuideStop {
  const place = places[placeKey];
  const {
    editorialUrls = [],
    mapQuery,
    sourceEvidence,
    sourceUrls = [],
    imageSourceUrl,
    officialUrl,
    bookingUrl,
    hours,
    ...rest
  } = options;
  const officialEvidence = officialUrl ?? place.officialUrl;
  const imageUrl = imageSourceUrl ?? place.photo;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${place.name} Marrakesh Morocco`);
  const allEditorialUrls = [...(place.editorialUrls ?? []), ...editorialUrls];
  const evidenceUrls = [officialEvidence, bookingUrl, mapUrl, imageUrl, ...allEditorialUrls, ...sourceUrls].filter(Boolean) as string[];

  return {
    id,
    name: place.name,
    coordinates: place.coordinates,
    description: `${place.fact} ${note}`,
    venueKind: "other",
    hours: hours ?? place.hours,
    photo: place.photo,
    imageSourceUrl: imageUrl,
    imageSourceName: imageUrl.includes("wikimedia.org") ? "Wikimedia Commons" : "Venue or cited editorial source",
    officialUrl: officialEvidence,
    ...(bookingUrl ? { bookingUrl } : {}),
    sourceUrls: [...new Set(evidenceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl: imageUrl,
      editorialUrls: allEditorialUrls,
      checkedAt,
      notes: "Official/property, map current-status, hours, and attributable image evidence checked on the listed date.",
      ...sourceEvidence,
    },
    ...rest,
  };
}

