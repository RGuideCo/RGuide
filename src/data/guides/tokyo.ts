type StopOptions = Partial<GuideStop> & {
  sourcePhoto: string;
  mapQuery?: string;
  editorialUrls?: string[];
};

function stop(id: string, name: string, coordinates: [number, number], description: string, options: StopOptions): GuideStop {
  const {
    sourcePhoto,
    mapQuery,
    editorialUrls = [],
    sourceEvidence,
    imageSourceUrl,
    officialUrl,
    bookingUrl,
    ...rest
  } = options;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${name} Tokyo`);
  const officialEvidence = sourceEvidence?.officialUrl ?? officialUrl ?? bookingUrl;
  const imageUrl = imageSourceUrl ?? sourcePhoto;
  const sourceUrls = [
    officialEvidence,
    mapUrl,
    imageUrl,
    ...editorialUrls,
    ...(options.sourceUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id,
    name,
    coordinates,
    description,
    hours: { default: "Open and active in the current source set; official page or Google Maps controls posted hours." },
    photo: sourcePhoto,
    imageSourceUrl: imageUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl: imageUrl,
      editorialUrls,
      checkedAt,
      notes: "Official or tourism source and Google Maps listing/search checked for current status; no permanent-closure warning found in the source set.",
      ...sourceEvidence,
    },
    ...(officialUrl ? { officialUrl } : {}),
    ...(bookingUrl ? { bookingUrl } : {}),
    ...rest,
  };
}

