function maps(query: string) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

function commons(fileName: string) {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(fileName)}?width=1600`;
}

function daily(hours: string): StopHours {
  return { default: `Daily ${hours}` };
}

function stop(input: StopInput): GuideStop {
  const mapUrl = maps(input.mapQuery ?? `${input.name} Seoul South Korea`);
  const platformUrls = [input.bookingUrl, ...(input.platformUrls ?? [])].filter(Boolean) as string[];
  const sourceUrls = [
    input.officialUrl,
    input.currentStatusUrl,
    mapUrl,
    input.photo,
    ...platformUrls,
    ...(input.editorialUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id: input.id,
    name: input.name,
    coordinates: input.coordinates,
    description: input.description,
    venueKind: input.venueKind,
    foodServiceType: input.foodServiceType,
    cuisineTypes: input.cuisineTypes,
    nightlifeType: input.nightlifeType,
    musicGenres: input.musicGenres,
    lodgingType: input.lodgingType,
    subcategory: input.subcategory,
    attributeTags: input.attributeTags,
    price: input.price,
    priceSource: input.priceSource,
    bookingUrl: input.bookingUrl,
    officialUrl: input.officialUrl,
    hours: input.hours,
    photo: input.photo,
    imageSourceUrl: input.photo,
    imageSourceName: input.photo.includes("wikimedia.org") ? "Wikimedia Commons" : undefined,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: input.officialUrl,
      mapUrl,
      currentStatusUrl: input.currentStatusUrl ?? mapUrl,
      imageSourceUrl: input.photo,
      editorialUrls: input.editorialUrls ?? [],
      platformUrls,
      checkedAt,
      notes: "Official venue or property information, current map evidence, and the linked editorial or booking sources were checked on the stated date. Hours summarize the named official schedule and explicit seasonal dependencies.",
    },
  };
}

