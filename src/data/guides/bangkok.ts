type StopInput = Partial<GuideStop> & {
  id: string;
  poiId: string;
  name: string;
  coordinates: [number, number];
  description: string;
  sourcePhoto?: string;
  officialUrl?: string;
  mapQuery?: string;
  editorialUrls?: string[];
  platformUrls?: string[];
};

function stop(input: StopInput): GuideStop {
  const {
    id,
    poiId,
    name,
    coordinates,
    description,
    sourcePhoto,
    mapQuery,
    editorialUrls = [],
    platformUrls = [],
    sourceEvidence,
    imageSourceUrl,
    officialUrl,
    bookingUrl,
    ...rest
  } = input;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${name} Bangkok Thailand`);
  const imageUrl = imageSourceUrl ?? sourcePhoto;
  const officialEvidence = sourceEvidence?.officialUrl ?? officialUrl ?? bookingUrl;
  const sourceUrls = [
    officialEvidence,
    mapUrl,
    imageUrl,
    ...editorialUrls,
    ...platformUrls,
    ...(input.sourceUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id,
    poiId,
    name,
    coordinates,
    description,
    photo: imageUrl,
    imageSourceUrl: imageUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl: imageUrl,
      editorialUrls,
      platformUrls,
      checkedAt,
      notes: "Official/property page and Google Maps search/listing checked for current status; no permanent-closure warning found in the source set.",
      ...sourceEvidence,
    },
    officialUrl,
    ...(bookingUrl ? { bookingUrl } : {}),
    ...rest,
  };
}

