type GuideSpec = {
  id: string;
  slug: string;
  seoSlug: string;
  seoTitle: string;
  seoDescription: string;
  title: string;
  description: string;
  category: ListCategory;
  sourceKey: keyof typeof sources;
  sourceKeys?: Array<keyof typeof sources>;
  stopIds: string[];
  stopDescriptions?: Partial<Record<string, string>>;
  routeCoordinates?: [number, number][];
  submissionType?: SubmissionType;
  neighborhood?: string;
};

function berlinMapUrl(name: string): string {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${name} Berlin`)}`;
}

function guide(spec: GuideSpec): MapList {
  const isDiveBarGuide = spec.seoSlug === "best-dive-bars";
  const guideSources = (spec.sourceKeys ?? [spec.sourceKey])
    .flatMap((sourceKey) => sources[sourceKey])
    .filter((source, index, allSources) => allSources.findIndex((candidate) => candidate.url === source.url) === index);

  return {
    id: spec.id,
    slug: spec.slug,
    seoSlug: spec.seoSlug,
    seoTitle: spec.seoTitle,
    seoDescription: spec.seoDescription,
    title: spec.title,
    description: spec.description,
    url: `https://www.google.com/maps/search/${encodeURIComponent(spec.seoTitle.toLowerCase())}`,
    category: spec.category,
    ...(spec.routeCoordinates ? { routeCoordinates: spec.routeCoordinates } : {}),
    ...(spec.submissionType ? { submissionType: spec.submissionType } : {}),
    location: spec.neighborhood
      ? { ...berlinLocation, neighborhood: spec.neighborhood }
      : berlinLocation,
    creator: {
      id: `user-rguide-${spec.category.toLowerCase()}`,
      name: `R ${spec.category}`,
      avatar: avatar(spec.category),
    },
    upvotes: 0,
    createdAt,
    stops: spec.stopIds.map((id) => {
      const base = stops[id];
      const stop = {
        ...base,
        ...(spec.stopDescriptions?.[id] ? { description: spec.stopDescriptions[id] } : {}),
        ...(spec.category === "Routes" ? { category: "Routes" as const } : {}),
        ...(isDiveBarGuide
          ? { attributeTags: ["dive_bars", ...(base.attributeTags ?? []).filter((tag) => tag !== "dive_bars")] }
          : {}),
        ...(berlinHoursByStop[id] ? { hours: berlinHoursByStop[id] } : {}),
      } satisfies GuideStop;

      const officialUrl = stop.officialUrl ?? stop.bookingUrl;
      const mapUrl = berlinMapUrl(stop.name);
      const imageSourceUrl = stop.imageSourceUrl ?? stop.photo;
      const sourceUrls = [...new Set([
        ...(stop.sourceUrls ?? []),
        officialUrl,
        mapUrl,
        imageSourceUrl,
      ].filter((url): url is string => Boolean(url)))];

      return {
        ...stop,
        imageSourceUrl,
        sourceUrls,
        sourceEvidence: {
          ...stop.sourceEvidence,
          officialUrl,
          mapUrl,
          currentStatusUrl: mapUrl,
          imageSourceUrl,
          notes: stop.sourceEvidence?.notes ?? "Official venue and venue-specific map evidence checked for current status.",
          checkedAt: stop.sourceEvidence?.checkedAt ?? "2026-07-23",
        },
      } satisfies GuideStop;
    }),
    sources: guideSources,
  };
}

