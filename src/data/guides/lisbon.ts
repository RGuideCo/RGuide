function stop(id: string, name: string, coordinates: [number, number], description: string, options: StopOptions): GuideStop {
  const {
    sourcePhoto,
    mapQuery,
    editorialUrls = [],
    sourceEvidence,
    imageSourceUrl,
    officialUrl,
    bookingUrl,
    ...rest
  } = options;
  const mapUrl = sourceEvidence?.mapUrl ?? maps(mapQuery ?? `${name} Lisbon Portugal`);
  const officialEvidence = sourceEvidence?.officialUrl ?? officialUrl ?? bookingUrl;
  const imageUrl = imageSourceUrl ?? sourcePhoto;
  const sourceUrls = [
    officialEvidence,
    mapUrl,
    imageUrl,
    ...editorialUrls,
    ...(options.sourceUrls ?? []),
  ].filter(Boolean) as string[];

  return {
    id,
    name,
    coordinates,
    description,
    hours: hoursByStopId[id] ?? {
      default: "Official site or maintained platform listing posts operating hours for this stop.",
    },
    photo: sourcePhoto,
    imageSourceUrl: imageUrl,
    sourceUrls: [...new Set(sourceUrls)],
    sourceEvidence: {
      officialUrl: officialEvidence,
      mapUrl,
      currentStatusUrl: mapUrl,
      imageSourceUrl: imageUrl,
      editorialUrls,
      checkedAt,
      notes: "Official/property page or maintained platform listing and Google Maps listing/search checked for current status; no permanent-closure warning found in the selected source set.",
      ...sourceEvidence,
    },
    ...(officialUrl ? { officialUrl } : {}),
    ...(bookingUrl ? { bookingUrl } : {}),
    ...rest,
  };
}

