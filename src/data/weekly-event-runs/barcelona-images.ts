function normalizeDocsBarcelonaTitle(value: string) {
  return value
    .replace(/&amp;/g, "&")
    .replace(/\+\s*(DT alk|gavina\.mp3|Mar Pujol).*$/i, "")
    .replace(/^Closing:\s*/i, "")
    .replace(/Audience award winner screening|Best film winner screening/i, "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function getBarcelonaWeeklyEventImage(title: string) {
  const normalizedTitle = normalizeDocsBarcelonaTitle(title);
  if (!normalizedTitle) {
    return undefined;
  }
  return officialDocsBarcelonaImageByTitle[normalizedTitle];
}
